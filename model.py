"""Failure-risk model: training, persistence and prediction.

The model is trained on SIMULATED data (see training_data.py). Metrics written by
`train()` measure how well the model recovers the simulator's rule on a held-out split.
They say nothing about performance on real machines.
"""
import json
from dataclasses import dataclass
from datetime import datetime, timezone
from functools import lru_cache

import joblib
import pandas as pd
import sklearn
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.inspection import permutation_importance
from sklearn.metrics import (
    average_precision_score,
    brier_score_loss,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import train_test_split

from . import config
from .training_data import make_training_data

PROVENANCE = (
    "Trained on simulated data generated by app/training_data.py. "
    "Metrics describe the held-out simulated split only, not real machines."
)


@dataclass
class ModelBundle:
    model: HistGradientBoostingClassifier
    meta: dict


def train(n: int = 8000, seed: int = 7, save: bool = True) -> ModelBundle:
    df = make_training_data(n, seed)
    X, y = df[config.FEATURES], df["failure"]
    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=0.25, stratify=y, random_state=seed
    )
    # Monotonic constraints encode basic physics: more heat, vibration or wear never lowers
    # risk, and slower speed never lowers it. This stops the trees flattening or reversing
    # at extreme values where the training data is sparse.
    monotonic = {"temperature_c": 1, "vibration_mm_s": 1, "rpm": -1, "operating_hours": 1}
    clf = HistGradientBoostingClassifier(
        max_iter=200, max_depth=3, learning_rate=0.06, min_samples_leaf=40,
        monotonic_cst=[monotonic[f] for f in config.FEATURES], random_state=seed,
    )
    clf.fit(X_tr, y_tr)
    perm = permutation_importance(clf, X_te, y_te, scoring="roc_auc", n_repeats=5, random_state=seed)

    proba = clf.predict_proba(X_te)[:, 1]
    pred = proba >= config.RISK_MEDIUM
    metrics = {
        "roc_auc": float(roc_auc_score(y_te, proba)),
        "average_precision": float(average_precision_score(y_te, proba)),
        "brier_score": float(brier_score_loss(y_te, proba)),
        "precision_at_medium_threshold": float(precision_score(y_te, pred, zero_division=0)),
        "recall_at_medium_threshold": float(recall_score(y_te, pred, zero_division=0)),
        "medium_threshold": config.RISK_MEDIUM,
        "n_train": int(len(X_tr)),
        "n_test": int(len(X_te)),
        "failure_rate_test": float(y_te.mean()),
    }

    healthy = df[df["condition"] < 0.3]
    baseline = {
        f: {"mean": float(healthy[f].mean()), "std": float(healthy[f].std())}
        for f in config.FEATURES
    }
    meta = {
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "algorithm": "HistGradientBoostingClassifier (monotonic constraints)",
        "features": config.FEATURES,
        "metrics": metrics,
        "baseline": baseline,
        "feature_importance": {
            f: float(v) for f, v in zip(config.FEATURES, perm.importances_mean)
        },
        "feature_importance_method": "permutation importance (drop in ROC AUC) on the held-out simulated split",
        "thresholds": {"medium": config.RISK_MEDIUM, "high": config.RISK_HIGH},
        "data_provenance": PROVENANCE,
        "sklearn_version": sklearn.__version__,
    }
    bundle = ModelBundle(clf, meta)
    if save:
        config.MODEL_DIR.mkdir(parents=True, exist_ok=True)
        joblib.dump(clf, config.MODEL_PATH)
        config.MODEL_META_PATH.write_text(json.dumps(meta, indent=2))
        get_bundle.cache_clear()
    return bundle


@lru_cache(maxsize=1)
def get_bundle() -> ModelBundle:
    """Load the saved model, training it first if it does not exist yet."""
    if config.MODEL_PATH.exists() and config.MODEL_META_PATH.exists():
        try:
            return ModelBundle(
                joblib.load(config.MODEL_PATH),
                json.loads(config.MODEL_META_PATH.read_text()),
            )
        except Exception:
            pass  # unreadable or version-mismatched file: retrain below
    return train()


def predict_probability(bundle: ModelBundle, values: dict) -> float:
    row = pd.DataFrame([{f: float(values[f]) for f in config.FEATURES}])
    return float(bundle.model.predict_proba(row)[0, 1])


def risk_level(p: float) -> str:
    if p >= config.RISK_HIGH:
        return "High"
    if p >= config.RISK_MEDIUM:
        return "Medium"
    return "Low"
